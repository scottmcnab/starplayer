/// Indexed by `(position >> 2) & 0x1F`; the sign comes from the position's own high bit,
/// so this is a quarter wave read forwards and a half wave read with a sign.
pub const VIBRATO_TABLE: [u8; 32] = [
       0,   24,   49,   74,   97,  120,  141,  161,  180,  197,  212,  224,  235,  244,  250,  253,
     255,  253,  250,  244,  235,  224,  212,  197,  180,  161,  141,  120,   97,   74,   49,   24,
];

/// FastTracker 2's arpeggio tick table.
///
/// The first sixteen entries are `i % 3`. The rest are **not** a continuation: FT2's table
/// is sixteen bytes long and its arpeggio reads `arpeggioTab[tick & 31]`, so a speed above
/// sixteen reads the sixteen bytes that follow the table in FT2's binary — which are the
/// first sixteen entries of [`VIBRATO_TABLE`]. `ft2-clone` confirms the same bytes on
/// FT2.08 and FT2.09 and OpenMPT reproduces them as `kFT2Arpeggio`. Every value above 1
/// selects the arpeggio's *second* nibble, and the `0` at index 16 selects the base note.
pub const ARPEGGIO_TICK_TABLE: [u8; 32] = [
       0,    1,    2,    0,    1,    2,    0,    1,    2,    0,    1,    2,    0,    1,    2,    0,
       0,   24,   49,   74,   97,  120,  141,  161,  180,  197,  212,  224,  235,  244,  250,  253,
];

/// The linear period at a note/finetune index: `(1936 - index) * 4`.
///
/// `index` is `note * 16 + ((finetune >> 3) + 16)` with `note` one-based from C-0, which is
/// FT2's `(note - 1) * 16 + (finetune >> 3) + 16` written without the cancelling terms. An
/// index past the table has no period; FT2 reads out of bounds there, and answering zero
/// puts it on FT2's own `period == 0` path, which is silence.
pub const fn linear_period(index: usize) -> u16 {
    match index < PERIOD_TABLE_LEN {
        true => ((PERIOD_TABLE_LEN - index) * 4) as u16,
        false => 0,
    }
}

/// The Amiga period at the same index, out of [`AMIGA_PERIOD_TABLE`].
pub const fn amiga_period(index: usize) -> u16 {
    // `AMIGA_PERIOD_TABLE.get(index)` is not `const`-callable on a slice index in this
    // edition, and the bound above is the same one `get` would apply.
    #[allow(clippy::indexing_slicing)]
    match index < PERIOD_TABLE_LEN {
        true => AMIGA_PERIOD_TABLE[index],
        false => 0,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_linear_period_formula_is_the_table_fast_tracker_two_stores() {
        assert_eq!(linear_period(0), 7744, "the first entry, a finetune below C-0");
        assert_eq!(linear_period(16 * 49), 4608, "C-4 with no finetune");
        assert_eq!(linear_period(16), 7680, "C-0 with no finetune, the first note of the table");
        assert_eq!(linear_period(PERIOD_TABLE_LEN - 1), 4);
        assert_eq!(linear_period(PERIOD_TABLE_LEN), 0, "past the table is FastTracker 2's zero period");
    }

    #[test]
    fn the_amiga_table_keeps_fast_tracker_twos_own_broken_tail() {
        assert_eq!(amiga_period(16 * 49), 1712, "C-4 is the format's own 1712");
        assert_eq!(amiga_period(0), 29024);
        assert_eq!(amiga_period(PERIOD_TABLE_LEN - 1), 0, "the buggy tail really does reach zero");
        assert_eq!(amiga_period(PERIOD_TABLE_LEN), 0);
        assert_eq!(AMIGA_PERIOD_TABLE.len(), PERIOD_TABLE_LEN);
    }

    #[test]
    fn the_arpeggio_table_runs_off_its_end_into_the_vibrato_table() {
        assert_eq!(&ARPEGGIO_TICK_TABLE[..16], &[0, 1, 2, 0, 1, 2, 0, 1, 2, 0, 1, 2, 0, 1, 2, 0]);
        assert_eq!(ARPEGGIO_TICK_TABLE[16], 0, "the overflow byte that still selects the base note");
        assert_eq!(&ARPEGGIO_TICK_TABLE[17..], &VIBRATO_TABLE[1..16], "the overflow is the vibrato table");
        assert_eq!(VIBRATO_TABLE[0], 0);
        assert_eq!(VIBRATO_TABLE[16], 255);
        assert_eq!(AUTO_VIBRATO_SINE_TABLE[0], 0);
        assert_eq!(AUTO_VIBRATO_SINE_TABLE[64], -64);
        assert_eq!(AUTO_VIBRATO_SINE_TABLE[192], 64);
    }
}
