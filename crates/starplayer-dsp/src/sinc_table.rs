//! The windowed-sinc coefficient table [`Sinc`](crate::Sinc) resamples through.
//!
//! # Generated data, committed as source
//!
//! Architecture §7.3 bans transcendental functions from the render path, so the table
//! cannot be built at start-up on an embedded target and must not be built per voice.
//! It is therefore **generated source**: [`SINC_TABLE_Q15`] below is the output of
//! [`tests::generate`], which runs only under `cargo test`, and
//! [`tests::the_committed_table_is_what_the_generator_produces`] regenerates it in `f64`
//! and asserts every coefficient. Editing the table by hand fails that test; changing the
//! filter means changing the generator and pasting its output back, which moves the
//! `sinc` golden by design.
//!
//! # The filter
//!
//! Eight taps at 256 phases — the sizes `starplayer_core::GUARD_FRAMES` was chosen for in
//! M2-task-C6 — of a sinc with its cutoff at [`SINC_CUTOFF`] of Nyquist, windowed by a
//! Kaiser window with β = [`SINC_KAISER_BETA`]. Each row is scaled to Q1.15 and its
//! largest tap is nudged so that the row sums to **exactly 32768**: DC gain is then
//! exactly unity on the fixed path, which is what stops a long loop from drifting in
//! level, and the fixed dot product needs one `round_shift_nearest` and no division.
//!
//! Task H5's research point 2 records why this window and this cutoff; see
//! [`Sinc`](crate::Sinc) for the measured numbers.

