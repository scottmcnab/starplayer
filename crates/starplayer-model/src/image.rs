    /// Leak `bytes` as a `'static` slice whose first byte is 4-byte aligned, which is what
    /// a firmware's `#[repr(C, align(4))]` wrapper around `include_bytes!` produces.
    ///
    /// Allocating as `u32` is the whole trick: `Box<[u8]>` promises alignment 1 only, so a
    /// test that leaked one would pass or fail on the allocator's mood.
    fn leak_aligned(bytes: &[u8]) -> &'static [u8] {
        let words: Vec<u32> = vec![0; bytes.len().div_ceil(4)];
        let leaked: &'static mut [u8] = bytemuck::cast_slice_mut(Vec::leak(words));
        let Some(head) = leaked.get_mut(..bytes.len()) else { return &[] };
        head.copy_from_slice(bytes);
        head
    }

    /// The same bytes one byte later in memory, so the PCM cannot be 4-byte aligned.
    fn leak_misaligned(bytes: &[u8]) -> &'static [u8] {
        let mut shifted = vec![0u8];
        shifted.extend_from_slice(bytes);
        leak_aligned(&shifted).get(1..).unwrap_or(&[])
    }

