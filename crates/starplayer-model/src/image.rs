//! The **module image** (`.spmi`): a built [`Module`] serialised so that a device can map
//! it in flash and play it without copying a single sample frame into RAM (M8-I2).
//!
//! # Why a second format at all
//!
//! The loaders are not the problem — the *copy* is. A loader turns a file into a `Module`
//! whose PCM is decoded, widened to `i16`, pre-rolled and guard-padded; on a 4 MB-flash
//! ESP32 with a few hundred KB of DRAM that finished blob is exactly what must not be
//! allocated. So the loader runs on the development machine (`cargo xtask module-image`),
//! the finished `Module` is written out with its PCM 4-byte aligned, the image is linked
//! into the firmware, and [`Module::from_image`] borrows the PCM and the pattern blob in
//! place. A load becomes a validation pass and four small index allocations.
//!
//! A module *uploaded at run time* still goes through the ordinary loader into the heap.
//! Both paths produce the same `Module`; only the storage differs.
//!
//! # The layout
//!
//! Flat, little-endian, read front to back. Every length is a `u32` and every one of them
//! is checked against the bytes actually present, so a truncated or lying image is an
//! [`Error`], never a panic.
//!
//! | Bytes | Field |
//! |---|---|
//! | 4 | magic [`IMAGE_MAGIC`] — `SPMI` |
//! | 2 | format version [`IMAGE_VERSION`] |
//! | 2 | flags, reserved, must be zero |
//! | … | the [`ModuleHeader`]: title, format, channel count, speed, tempo, volumes, pan table, flags, dialect, `format_extra`, channel-volume table, `format_data` — each variable-length field length-prefixed |
//! | 16 | counts: samples, patterns, orders, instruments |
//! | … | the sample table ([`SampleIndex`] per entry, name length-prefixed) |
//! | … | the pattern table ([`PatternIndex`] per entry) |
//! | … | the order list, one `u16` each |
//! | … | the instrument table ([`InstrumentDef`] per entry; envelopes length-prefixed, and each 120-entry note map written only when it differs from the default) |
//! | 4 + n | the pattern blob: length in bytes, then the bytes |
//! | 0–3 | zero padding to a 4-byte boundary |
//! | 4 | PCM length, in **frames** |
//! | 2n | the PCM, `i16` little-endian, starting at a 4-byte-aligned offset |
//!
//! # The version rule
//!
//! **Any change to the layout above bumps [`IMAGE_VERSION`].** The reader rejects a
//! version it does not know with [`Error::Unsupported`] rather than reading a field at the
//! wrong offset. There is no forward compatibility and none is wanted: an image is a build
//! product regenerated by `cargo xtask module-images`, not an interchange format, and a
//! stale one in a firmware is a bug that should fail loudly at boot.
//!
//! # Little-endian only, deliberately
//!
//! The point of the format is that the borrowed `i16` slice is the device's PCM, read with
//! no conversion pass. That works because both targets — Xtensa LX6 and RISC-V — are
//! little-endian, as are x86-64, aarch64 and wasm32. On a big-endian host
//! [`Module::from_image`] refuses rather than handing back silently byte-swapped audio;
//! [`Module::from_image_copied`] still works there, because it decodes each frame from
//! explicit little-endian bytes.
//!
//! # Three ways in, named honestly
//!
//! | Constructor | Blob | PCM | Wants |
//! |---|---|---|---|
//! | [`Module::from_image`] | borrowed | borrowed, or `Err` | a 4-byte-aligned `&'static [u8]` |
//! | [`Module::from_image_or_copy`] | borrowed | borrowed when it can be, else copied | any `&'static [u8]` |
//! | [`Module::from_image_copied`] | copied | copied | any `&[u8]`, any alignment, any endianness |
//!
//! Bytes **after** the PCM are ignored rather than rejected, so a firmware may hand a whole
//! flash partition — padded out to its erase-block size — straight to the reader without
//! having to know where the image ends. Everything up to that point is length-checked, and
//! the alignment padding before the PCM must be zero, so nothing can be smuggled through
//! the middle of an image; only past the end of one, where nothing reads it.
//!
//! `include_bytes!` yields a `&'static [u8]` of alignment **1**, so a firmware must place
//! the image behind a `#[repr(C, align(4))]` wrapper (the standard trick) or in an aligned
//! flash partition. [`Module::from_image`] is the constructor that proves it did:
//! misalignment is an `Err`, never a silent copy. [`Module::from_image_or_copy`] is for the
//! caller that would rather spend the RAM than fail to play — a run-time flash partition
//! whose alignment it does not control.

