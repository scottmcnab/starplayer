    fn from_image_or_copy_takes_a_misaligned_image_and_copies_only_the_pcm() {
        let module = exhaustive_module();
        let bytes = module.to_image();
        let recovered = Module::from_image_or_copy(leak_misaligned(&bytes)).expect("the fallback reads a misaligned image");

        assert_eq!(recovered, module);
        assert!(!recovered.pcm_storage().is_borrowed(), "the PCM is the part that had to be copied");
        assert!(recovered.blob_storage().is_borrowed(), "bytes have no alignment to lose, so the blob still borrows");
    }

    #[test]
    fn from_image_or_copy_still_borrows_an_aligned_image() {
        let module = exhaustive_module();
        let image = leak_aligned(&module.to_image());
        let borrowed = Module::from_image_or_copy(image).expect("the image reads back");

        assert!(borrowed.pcm_storage().is_borrowed(), "the fallback must not copy what it could borrow");
    }

    #[test]
    fn a_borrowed_module_rebuilds_into_an_equal_owned_module() {
        let module = exhaustive_module();
        let borrowed = Module::from_image(leak_aligned(&module.to_image())).expect("the image reads back");
        let rebuilt = borrowed.enhanced(&Identity).expect("an identity rebuild");

        assert_eq!(rebuilt, module, "K5a's identity-rebuild equality must hold across borrowed storage");
        assert!(!rebuilt.pcm_storage().is_borrowed(), "a rebuild goes through the builder, which always owns");
    }

    #[test]
    fn a_clone_of_a_borrowed_module_stays_borrowed() {
        let module = exhaustive_module();
        let borrowed = Module::from_image(leak_aligned(&module.to_image())).expect("the image reads back");
        let cloned = borrowed.clone();

        assert!(cloned.pcm_storage().is_borrowed());
        assert_eq!(cloned, borrowed);
    }

