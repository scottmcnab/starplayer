/// The four bytes every module image starts with.
pub const IMAGE_MAGIC: [u8; 4] = *b"SPMI";

/// The layout version this build writes, and the only one it reads. See the
/// [module documentation](self) for the version rule.
pub const IMAGE_VERSION: u16 = 1;

/// Alignment the PCM region is written at, and the alignment
/// [`Module::from_image`] requires of the whole image in memory.
///
/// `i16` needs only 2, but 4 is what a word-addressed flash mapping wants and what a
/// `#[repr(C, align(4))]` wrapper around `include_bytes!` gives, so the format pins the
/// larger number and the reader checks it.
pub const IMAGE_ALIGNMENT: usize = 4;

const MISALIGNED: Error = Error::Invalid("a module image must be 4-byte aligned in memory to borrow its PCM");
const RESERVED_FLAGS: Error = Error::Invalid("a module image's reserved flags must be zero");
const BAD_ENUM: Error = Error::Invalid("a module image names an enum value this build does not have");
const BAD_BOOL: Error = Error::Invalid("a module image's boolean byte is neither 0 nor 1");
const BAD_TEXT: Error = Error::Invalid("a module image's text is not valid UTF-8");
const BAD_PADDING: Error = Error::Invalid("a module image's alignment padding is not zero");

/// Smallest number of bytes one entry of each table can occupy, used to reject an absurd
/// count **before** anything is allocated for it. The exact sizes do not matter; that they
/// are non-zero and no larger than the real entry does.
const MINIMUM_SAMPLE_BYTES: usize = 36;
const MINIMUM_PATTERN_BYTES: usize = 11;
const MINIMUM_ORDER_BYTES: usize = 2;
const MINIMUM_INSTRUMENT_BYTES: usize = 30;
const MINIMUM_ENVELOPE_POINT_BYTES: usize = 4;

// ── reading ─────────────────────────────────────────────────────────────────────────

impl Module {
    /// Build a module that **borrows** its PCM and its pattern blob from a memory-mapped
    /// image.
    ///
    /// The image is validated to exactly the standard
    /// [`ModuleBuilder::build`](crate::ModuleBuilder::build) applies — the same
    /// `Module::validate` runs over the decoded index tables — because the engine reads a
    /// `Module` from inside `render()`, where an out-of-range offset would be a panic in
    /// the audio callback. Nothing here panics, on any input.
    ///
    /// # Errors
    ///
    /// * [`Error::BadMagic`] — the image does not begin with [`IMAGE_MAGIC`].
    /// * [`Error::Unsupported`] — the image's version is not [`IMAGE_VERSION`], or the host
    ///   is big-endian and the PCM therefore cannot be borrowed.
    /// * [`Error::Invalid`] — the image is not 4-byte aligned in memory, or a field is not
    ///   a value this build has (an enum code, a boolean byte, non-UTF-8 text), or an
    ///   invariant [`ModuleBuilder::build`](crate::ModuleBuilder::build) enforces is
    ///   broken.
    /// * [`Error::Truncated`] — a length field names more bytes than the image holds.
    /// * [`Error::OutOfRange`] — an index table points outside the blob it indexes.
    pub fn from_image(image: &'static [u8]) -> Result<Module, Error> {
        let parts = parse_image(image)?;
        let blob = image.get(parts.blob_bytes.clone()).ok_or(Error::OutOfRange)?;
        let pcm_bytes = image.get(parts.pcm_bytes.clone()).ok_or(Error::OutOfRange)?;
        let pcm = borrow_frames(pcm_bytes)?;
        parts.into_module(BlobStorage::Borrowed(blob), PcmStorage::Borrowed(pcm))
    }

    /// [`Module::from_image`], but an image whose PCM cannot be borrowed — because the
    /// image is not 4-byte aligned, or the host is big-endian — has **only its PCM**
    /// copied onto the heap rather than being refused. The pattern blob is borrowed
    /// either way; it is bytes, so its alignment is never in question.
    ///
    /// Use it where the alignment of the mapping is not yours to choose, such as a module
    /// image written into a flash partition at run time. Where it *is* yours — an image
    /// linked in with `include_bytes!` behind a `#[repr(C, align(4))]` wrapper —
    /// [`Module::from_image`] is the better call, because it fails rather than quietly
    /// spending the RAM the whole exercise was meant to save.
    ///
    /// # Errors
    ///
    /// As [`Module::from_image`], less the alignment and endianness cases it handles.
    pub fn from_image_or_copy(image: &'static [u8]) -> Result<Module, Error> {
        let parts = parse_image(image)?;
        let blob = image.get(parts.blob_bytes.clone()).ok_or(Error::OutOfRange)?;
        let pcm_bytes = image.get(parts.pcm_bytes.clone()).ok_or(Error::OutOfRange)?;
        let pcm = match borrow_frames(pcm_bytes) {
            Ok(borrowed) => PcmStorage::Borrowed(borrowed),
            Err(_) => PcmStorage::Owned(copy_frames(pcm_bytes)),
        };
        parts.into_module(BlobStorage::Borrowed(blob), pcm)
    }

    /// Read an image into an **owned** module, copying both blobs.
    ///
    /// The entry point for bytes that are not `'static` — a file read into a `Vec`, an
    /// image uploaded over the network — and the one that works on a big-endian host,
    /// since it decodes every frame from explicit little-endian bytes. The module it
    /// produces is indistinguishable from the one the loader built: same tables, same
    /// blobs, equal and hashing alike.
    ///
    /// # Errors
    ///
    /// As [`Module::from_image`], less the alignment and endianness cases it cannot hit.
    pub fn from_image_copied(image: &[u8]) -> Result<Module, Error> {
        let parts = parse_image(image)?;
        let blob = image.get(parts.blob_bytes.clone()).ok_or(Error::OutOfRange)?;
        let pcm_bytes = image.get(parts.pcm_bytes.clone()).ok_or(Error::OutOfRange)?;
        let blob = BlobStorage::Owned(Box::from(blob));
        parts.into_module(blob, PcmStorage::Owned(copy_frames(pcm_bytes)))
    }
}

/// Everything an image holds except the two blobs, which stay as byte ranges into the
/// image so that each constructor above can decide how to hold them.
struct ImageParts {
    header: ModuleHeader,
    samples: Box<[SampleIndex]>,
    patterns: Box<[PatternIndex]>,
    orders: Box<[u16]>,
    instruments: Box<[InstrumentDef]>,
    blob_bytes: Range<usize>,
    pcm_bytes: Range<usize>,
}

impl ImageParts {
    /// Assemble the module and run the model's own invariant check over it — the same one
    /// [`ModuleBuilder::build`](crate::ModuleBuilder::build) runs, so a module that came
    /// out of an image has passed exactly what a loaded module passed.
    fn into_module(self, blob: BlobStorage, pcm: PcmStorage) -> Result<Module, Error> {
        let module = Module::from_parts(blob, pcm, self.samples, self.patterns, self.orders, self.instruments, self.header);
        module.validate()?;
        Ok(module)
    }
}

/// Borrow the PCM region as `i16` frames, or say why it cannot be borrowed.
#[cfg(target_endian = "little")]
fn borrow_frames(bytes: &'static [u8]) -> Result<&'static [i16], Error> {
    if !(bytes.as_ptr() as usize).is_multiple_of(IMAGE_ALIGNMENT) {
        return Err(MISALIGNED);
    }
    // The cast can still refuse — it checks `align_of::<i16>()` and the length itself —
    // and a refusal is reported rather than worked around, because a silent copy here is
    // precisely the RAM cost this format exists to avoid.
    bytemuck::try_cast_slice(bytes).map_err(|_| MISALIGNED)
}

/// On a big-endian host the borrowed frames would be byte-swapped audio, so there is no
/// borrow to hand back. See the [module documentation](self).
#[cfg(target_endian = "big")]
fn borrow_frames(_bytes: &'static [u8]) -> Result<&'static [i16], Error> {
    Err(Error::Unsupported("a module image's PCM can only be borrowed on a little-endian host"))
}

/// Decode the PCM region into owned frames, from explicit little-endian bytes so the
/// result is the same on every host.
fn copy_frames(bytes: &[u8]) -> Box<[i16]> {
    let frames: Vec<i16> = bytes
        .chunks_exact(2)
        // `chunks_exact(2)` only ever yields two bytes, so the `Err` arm is unreachable;
        // it is written as a fallback rather than an `unwrap` because this crate forbids
        // both panicking and indexing.
        .map(|pair| match <[u8; 2]>::try_from(pair) {
            Ok(pair) => i16::from_le_bytes(pair),
            Err(_) => 0,
        })
        .collect();
    frames.into_boxed_slice()
}

/// A bounds-checked forward cursor over the image. Every read either advances or returns
/// [`Error::Truncated`] naming where it ran out.
struct Cursor<'image> {
    bytes: &'image [u8],
    offset: usize,
}

impl<'image> Cursor<'image> {
    fn new(bytes: &'image [u8]) -> Cursor<'image> { Cursor { bytes, offset: 0 } }

    fn remaining(&self) -> usize { self.bytes.len().saturating_sub(self.offset) }

    fn take(&mut self, length: usize) -> Result<&'image [u8], Error> {
        let truncated = Error::Truncated { offset: self.offset, needed: length };
        let end = self.offset.checked_add(length).ok_or(truncated)?;
        let slice = self.bytes.get(self.offset..end).ok_or(truncated)?;
        self.offset = end;
        Ok(slice)
    }

    /// The byte range `length` bytes from here occupies, skipping over it. The range is
    /// how a blob reaches its storage without being copied first.
    fn take_range(&mut self, length: usize) -> Result<Range<usize>, Error> {
        let start = self.offset;
        self.take(length)?;
        Ok(start..self.offset)
    }

    fn u8(&mut self) -> Result<u8, Error> {
        let bytes = self.take(1)?;
        bytes.first().copied().ok_or(Error::Truncated { offset: self.offset, needed: 1 })
    }

    fn i8(&mut self) -> Result<i8, Error> { Ok(self.u8()? as i8) }

    fn u16(&mut self) -> Result<u16, Error> {
        let bytes = <[u8; 2]>::try_from(self.take(2)?).map_err(|_| Error::Truncated { offset: self.offset, needed: 2 })?;
        Ok(u16::from_le_bytes(bytes))
    }

    fn i16(&mut self) -> Result<i16, Error> { Ok(self.u16()? as i16) }

    fn u32(&mut self) -> Result<u32, Error> {
        let bytes = <[u8; 4]>::try_from(self.take(4)?).map_err(|_| Error::Truncated { offset: self.offset, needed: 4 })?;
        Ok(u32::from_le_bytes(bytes))
    }

    fn boolean(&mut self) -> Result<bool, Error> {
        match self.u8()? {
            0 => Ok(false),
            1 => Ok(true),
            _ => Err(BAD_BOOL),
        }
    }

    /// A `u32` length followed by that many bytes of UTF-8.
    fn text(&mut self) -> Result<Box<str>, Error> {
        let length = self.length()?;
        let bytes = self.take(length)?;
        let text = core::str::from_utf8(bytes).map_err(|_| BAD_TEXT)?;
        Ok(String::from(text).into_boxed_str())
    }

    /// A `u32` byte length, as a `usize`.
    fn length(&mut self) -> Result<usize, Error> { Ok(self.u32()? as usize) }

    /// A `u32` entry count, refused **before** anything is allocated for it if the image
    /// is too short to hold that many entries of `minimum_entry_bytes`.
    ///
    /// Without this a four-byte count of `0xFFFF_FFFF` would ask for gigabytes from a
    /// forty-byte input, which is the shape of every fuzzer-found allocation blowup.
    fn count(&mut self, minimum_entry_bytes: usize) -> Result<usize, Error> {
        let count = self.u32()? as usize;
        let needed = count.checked_mul(minimum_entry_bytes).ok_or(Error::Truncated { offset: self.offset, needed: usize::MAX })?;
        if needed > self.remaining() {
            return Err(Error::Truncated { offset: self.offset, needed });
        }
        Ok(count)
    }

    /// Skip zero padding up to the next [`IMAGE_ALIGNMENT`] boundary. The padding must be
    /// zero, so an image cannot smuggle anything through it.
    fn align(&mut self) -> Result<(), Error> {
        let padding = (IMAGE_ALIGNMENT - self.offset % IMAGE_ALIGNMENT) % IMAGE_ALIGNMENT;
        if self.take(padding)?.iter().any(|byte| *byte != 0) {
            return Err(BAD_PADDING);
        }
        Ok(())
    }
}

fn parse_image(image: &[u8]) -> Result<ImageParts, Error> {
    let mut cursor = Cursor::new(image);
    if cursor.take(IMAGE_MAGIC.len())? != IMAGE_MAGIC {
        return Err(Error::BadMagic);
    }
    if cursor.u16()? != IMAGE_VERSION {
        return Err(Error::Unsupported("a module image of a layout version this build does not read"));
    }
    if cursor.u16()? != 0 {
        return Err(RESERVED_FLAGS);
    }

    let header = read_header(&mut cursor)?;
    let sample_count = cursor.count(MINIMUM_SAMPLE_BYTES)?;
    let pattern_count = cursor.count(MINIMUM_PATTERN_BYTES)?;
    let order_count = cursor.count(MINIMUM_ORDER_BYTES)?;
    let instrument_count = cursor.count(MINIMUM_INSTRUMENT_BYTES)?;

    let mut samples = Vec::with_capacity(sample_count);
    for _ in 0..sample_count {
        samples.push(read_sample(&mut cursor)?);
    }
    let mut patterns = Vec::with_capacity(pattern_count);
    for _ in 0..pattern_count {
        patterns.push(read_pattern(&mut cursor)?);
    }
    let mut orders = Vec::with_capacity(order_count);
    for _ in 0..order_count {
        orders.push(cursor.u16()?);
    }
    let mut instruments = Vec::with_capacity(instrument_count);
    for _ in 0..instrument_count {
        instruments.push(read_instrument(&mut cursor)?);
    }

    let blob_length = cursor.length()?;
    let blob_bytes = cursor.take_range(blob_length)?;
    cursor.align()?;
    let pcm_frames = cursor.length()?;
    let pcm_length = pcm_frames.checked_mul(2).ok_or(Error::TooLarge("a module image's PCM length"))?;
    let pcm_bytes = cursor.take_range(pcm_length)?;

    Ok(ImageParts {
        header,
        samples: samples.into_boxed_slice(),
        patterns: patterns.into_boxed_slice(),
        orders: orders.into_boxed_slice(),
        instruments: instruments.into_boxed_slice(),
        blob_bytes,
        pcm_bytes,
    })
}

fn read_header(cursor: &mut Cursor<'_>) -> Result<ModuleHeader, Error> {
    let title = cursor.text()?;
    let format = module_format_from_code(cursor.u8()?)?;
    let channel_count = cursor.u8()?;
    let initial_speed = cursor.u8()?;
    let flags = read_module_flags(cursor.u8()?)?;
    let initial_tempo = cursor.u16()?;
    let global_volume = U0F16::from_bits(cursor.u16()?);
    let master_volume = U0F16::from_bits(cursor.u16()?);
    let dialect = dialect_from_code(cursor.u16()?)?;
    let format_extra = cursor.u32()?;

    let pan_count = cursor.count(2)?;
    let mut default_pan = Vec::with_capacity(pan_count);
    for _ in 0..pan_count {
        default_pan.push(I1F15::from_bits(cursor.i16()?));
    }
    let channel_volume_count = cursor.count(2)?;
    let mut default_channel_volume = Vec::with_capacity(channel_volume_count);
    for _ in 0..channel_volume_count {
        default_channel_volume.push(U0F16::from_bits(cursor.u16()?));
    }
    let format_data_length = cursor.length()?;
    let format_data = Box::from(cursor.take(format_data_length)?);

    Ok(ModuleHeader {
        title,
        format,
        channel_count,
        initial_speed,
        initial_tempo,
        global_volume,
        master_volume,
        default_pan: default_pan.into_boxed_slice(),
        flags,
        dialect,
        format_extra,
        default_channel_volume: default_channel_volume.into_boxed_slice(),
        format_data,
    })
}

fn read_sample(cursor: &mut Cursor<'_>) -> Result<SampleIndex, Error> {
    let pcm_offset = cursor.u32()?;
    let length_frames = cursor.u32()?;
    let specification = SampleSpec {
        loop_mode: loop_mode_from_code(cursor.u8()?)?,
        loop_start: cursor.u32()?,
        loop_end: cursor.u32()?,
        default_volume: U0F16::from_bits(cursor.u16()?),
        reference_rate_hz: cursor.u32()?,
        relative_note: cursor.i8()?,
        finetune: cursor.i8()?,
        default_pan: read_optional_pan(cursor)?,
        auto_vibrato: AutoVibrato {
            waveform: auto_vibrato_waveform_from_code(cursor.u8()?)?,
            sweep: cursor.u8()?,
            depth: cursor.u8()?,
            rate: cursor.u8()?,
        },
        sustain_loop: read_optional_sustain_loop(cursor)?,
        rate_scale_log2: cursor.u8()?,
        name: String::from(cursor.text()?),
    };
    Ok(SampleIndex::new(pcm_offset, length_frames, specification))
}

fn read_pattern(cursor: &mut Cursor<'_>) -> Result<PatternIndex, Error> {
    let blob_offset = cursor.u32()?;
    let length_bytes = cursor.u32()?;
    let rows = cursor.u16()?;
    let channels = cursor.u8()?;
    Ok(PatternIndex::new(blob_offset, length_bytes, rows, channels))
}

fn read_instrument(cursor: &mut Cursor<'_>) -> Result<InstrumentDef, Error> {
    let name = cursor.text()?;
    // The id is written whether or not the instrument has one, so it is read either way
    // too: an `Option` costs a fixed three bytes here, never a variable-length field.
    let present = cursor.boolean()?;
    let sample = present.then_some(SampleId(cursor.u16()?));
    let default_volume = U0F16::from_bits(cursor.u16()?);

    let mut note_sample_map = [0u16; NOTE_MAP_LENGTH];
    if cursor.boolean()? {
        for entry in note_sample_map.iter_mut() {
            *entry = cursor.u16()?;
        }
    }
    let mut note_transpose_map = identity_transpose_map();
    if cursor.boolean()? {
        for entry in note_transpose_map.iter_mut() {
            *entry = cursor.u8()?;
        }
    }

    let volume_envelope = read_optional_envelope(cursor)?;
    let panning_envelope = read_optional_envelope(cursor)?;
    let pitch_envelope = read_optional_envelope(cursor)?;
    let fadeout = cursor.u16()?;
    let new_note_action = new_note_action_from_code(cursor.u8()?)?;
    let duplicate_check = duplicate_check_from_code(cursor.u8()?)?;
    let duplicate_action = duplicate_action_from_code(cursor.u8()?)?;
    let global_volume = U0F16::from_bits(cursor.u16()?);
    let default_pan = read_optional_pan(cursor)?;
    let pitch_pan_separation = cursor.i8()?;
    let pitch_pan_centre = cursor.u8()?;
    let random_volume_variation = cursor.u8()?;
    let random_pan_variation = cursor.u8()?;
    let initial_filter_cutoff = read_optional_byte(cursor)?;
    let initial_filter_resonance = read_optional_byte(cursor)?;
    let pitch_envelope_is_filter = cursor.boolean()?;

    Ok(InstrumentDef {
        name,
        sample,
        default_volume,
        note_sample_map,
        note_transpose_map,
        volume_envelope,
        panning_envelope,
        pitch_envelope,
        fadeout,
        new_note_action,
        duplicate_check,
        duplicate_action,
        global_volume,
        default_pan,
        pitch_pan_separation,
        pitch_pan_centre,
        random_volume_variation,
        random_pan_variation,
        initial_filter_cutoff,
        initial_filter_resonance,
        pitch_envelope_is_filter,
    })
}

fn read_optional_envelope(cursor: &mut Cursor<'_>) -> Result<Option<Envelope>, Error> {
    if !cursor.boolean()? {
        return Ok(None);
    }
    let point_count = cursor.count(MINIMUM_ENVELOPE_POINT_BYTES)?;
    let mut points = Vec::with_capacity(point_count);
    for _ in 0..point_count {
        points.push(EnvelopePoint { tick: cursor.u16()?, value: cursor.i16()? });
    }
    let sustain = read_optional_span(cursor)?;
    let loop_span = read_optional_span(cursor)?;
    let carry = cursor.boolean()?;
    Ok(Some(Envelope { points: points.into_boxed_slice(), sustain, loop_span, carry }))
}

fn read_optional_span(cursor: &mut Cursor<'_>) -> Result<Option<EnvelopeSpan>, Error> {
    let present = cursor.boolean()?;
    let span = EnvelopeSpan { start: cursor.u8()?, end: cursor.u8()? };
    Ok(present.then_some(span))
}

fn read_optional_pan(cursor: &mut Cursor<'_>) -> Result<Option<I1F15>, Error> {
    let present = cursor.boolean()?;
    let pan = I1F15::from_bits(cursor.i16()?);
    Ok(present.then_some(pan))
}

fn read_optional_byte(cursor: &mut Cursor<'_>) -> Result<Option<u8>, Error> {
    let present = cursor.boolean()?;
    let value = cursor.u8()?;
    Ok(present.then_some(value))
}

fn read_optional_sustain_loop(cursor: &mut Cursor<'_>) -> Result<Option<SustainLoop>, Error> {
    let present = cursor.boolean()?;
    let sustain = SustainLoop { mode: loop_mode_from_code(cursor.u8()?)?, start: cursor.u32()?, end: cursor.u32()? };
    Ok(present.then_some(sustain))
}

fn read_module_flags(bits: u8) -> Result<ModuleFlags, Error> {
    const KNOWN: u8 = 0b0000_1111;
    if bits & !KNOWN != 0 {
        return Err(RESERVED_FLAGS);
    }
    Ok(ModuleFlags {
        amiga_limits: bits & 0b0001 != 0,
        linear_slides: bits & 0b0010 != 0,
        fast_volume_slides: bits & 0b0100 != 0,
        stereo: bits & 0b1000 != 0,
    })
}

// ── writing ─────────────────────────────────────────────────────────────────────────

impl Module {
    /// Serialise this module as a module image — the inverse of [`Module::from_image`].
    ///
    /// Host-side only in practice (`cargo xtask module-image` is its one caller), but not
    /// feature-gated: it is a plain function over `alloc`, so a firmware that never calls
    /// it never links it, and a feature would have cost every test and every tool a flag
    /// for nothing.
    ///
    /// Every length is written as a `u32` and a length that would not fit saturates, which
    /// the reader then rejects as [`Error::Truncated`] — so a module too large for the
    /// format produces an image that fails to load rather than one that loads wrongly. No
    /// module any loader in this workspace can produce is anywhere near that: the model's
    /// own offsets are `u32` already.
    pub fn to_image(&self) -> Vec<u8> {
        let mut image = Vec::new();
        image.extend_from_slice(&IMAGE_MAGIC);
        push_u16(&mut image, IMAGE_VERSION);
        push_u16(&mut image, 0);

        write_header(&mut image, self.header());
        push_length(&mut image, self.samples().len());
        push_length(&mut image, self.patterns().len());
        push_length(&mut image, self.orders().len());
        push_length(&mut image, self.instruments().len());

        for sample in self.samples().iter() {
            write_sample(&mut image, sample);
        }
        for pattern in self.patterns().iter() {
            write_pattern(&mut image, pattern);
        }
        for order in self.orders().iter() {
            push_u16(&mut image, *order);
        }
        for instrument in self.instruments().iter() {
            write_instrument(&mut image, instrument);
        }

        push_length(&mut image, self.blob().len());
        image.extend_from_slice(self.blob());
        // The PCM's own length field is four bytes, so aligning *before* it is what lands
        // the frames themselves on a 4-byte boundary.
        while !image.len().is_multiple_of(IMAGE_ALIGNMENT) {
            image.push(0);
        }
        push_length(&mut image, self.pcm().len());
        for frame in self.pcm().iter() {
            image.extend_from_slice(&frame.to_le_bytes());
        }
        image
    }

    /// How many bytes of `to_image`'s output are sample frames — the number that decides
    /// whether a module fits a flash partition, and the one an `i8` storage would halve
    /// (M8-I2 research point 2).
    pub fn image_pcm_bytes(&self) -> usize { self.pcm().len().saturating_mul(2) }
}

fn write_header(image: &mut Vec<u8>, header: &ModuleHeader) {
    push_text(image, &header.title);
    image.push(module_format_code(header.format));
    image.push(header.channel_count);
    image.push(header.initial_speed);
    image.push(module_flags_bits(header.flags));
    push_u16(image, header.initial_tempo);
    push_u16(image, header.global_volume.to_bits());
    push_u16(image, header.master_volume.to_bits());
    push_u16(image, dialect_code(header.dialect));
    push_u32(image, header.format_extra);

    push_length(image, header.default_pan.len());
    for pan in header.default_pan.iter() {
        push_u16(image, pan.to_bits() as u16);
    }
    push_length(image, header.default_channel_volume.len());
    for volume in header.default_channel_volume.iter() {
        push_u16(image, volume.to_bits());
    }
    push_length(image, header.format_data.len());
    image.extend_from_slice(&header.format_data);
}

fn write_sample(image: &mut Vec<u8>, sample: &SampleIndex) {
    let specification = sample.to_spec();
    push_u32(image, sample.pcm_offset());
    push_u32(image, sample.length_frames());
    image.push(loop_mode_code(specification.loop_mode));
    push_u32(image, specification.loop_start);
    push_u32(image, specification.loop_end);
    push_u16(image, specification.default_volume.to_bits());
    push_u32(image, specification.reference_rate_hz);
    image.push(specification.relative_note as u8);
    image.push(specification.finetune as u8);
    write_optional_pan(image, specification.default_pan);
    image.push(auto_vibrato_waveform_code(specification.auto_vibrato.waveform));
    image.push(specification.auto_vibrato.sweep);
    image.push(specification.auto_vibrato.depth);
    image.push(specification.auto_vibrato.rate);
    write_optional_sustain_loop(image, specification.sustain_loop);
    image.push(specification.rate_scale_log2);
    push_text(image, &specification.name);
}

fn write_pattern(image: &mut Vec<u8>, pattern: &PatternIndex) {
    push_u32(image, pattern.blob_offset());
    push_u32(image, pattern.length_bytes());
    push_u16(image, pattern.rows());
    image.push(pattern.channels());
}

fn write_instrument(image: &mut Vec<u8>, instrument: &InstrumentDef) {
    push_text(image, &instrument.name);
    match instrument.sample {
        Some(SampleId(sample)) => {
            image.push(1);
            push_u16(image, sample);
        }
        None => {
            image.push(0);
            push_u16(image, 0);
        }
    }
    push_u16(image, instrument.default_volume.to_bits());
    // The two 120-entry note maps are written only when they are not the default an
    // MOD/S3M/MTM instrument always carries — all-zero, and the identity transpose. That
    // is 360 bytes saved per instrument, which on a 31-instrument MOD is most of the
    // image; see `Module::to_image`.
    let note_sample_map_is_default = instrument.note_sample_map.iter().all(|entry| *entry == 0);
    image.push(u8::from(!note_sample_map_is_default));
    if !note_sample_map_is_default {
        for entry in instrument.note_sample_map.iter() {
            push_u16(image, *entry);
        }
    }
    let note_transpose_map_is_default = instrument.note_transpose_map == identity_transpose_map();
    image.push(u8::from(!note_transpose_map_is_default));
    if !note_transpose_map_is_default {
        image.extend_from_slice(&instrument.note_transpose_map);
    }

    write_optional_envelope(image, instrument.volume_envelope.as_ref());
    write_optional_envelope(image, instrument.panning_envelope.as_ref());
    write_optional_envelope(image, instrument.pitch_envelope.as_ref());
    push_u16(image, instrument.fadeout);
    image.push(new_note_action_code(instrument.new_note_action));
    image.push(duplicate_check_code(instrument.duplicate_check));
    image.push(duplicate_action_code(instrument.duplicate_action));
    push_u16(image, instrument.global_volume.to_bits());
    write_optional_pan(image, instrument.default_pan);
    image.push(instrument.pitch_pan_separation as u8);
    image.push(instrument.pitch_pan_centre);
    image.push(instrument.random_volume_variation);
    image.push(instrument.random_pan_variation);
    write_optional_byte(image, instrument.initial_filter_cutoff);
    write_optional_byte(image, instrument.initial_filter_resonance);
    image.push(u8::from(instrument.pitch_envelope_is_filter));
}

fn write_optional_envelope(image: &mut Vec<u8>, envelope: Option<&Envelope>) {
    let Some(envelope) = envelope else {
        image.push(0);
        return;
    };
    image.push(1);
    push_length(image, envelope.points.len());
    for point in envelope.points.iter() {
        push_u16(image, point.tick);
        push_u16(image, point.value as u16);
    }
    write_optional_span(image, envelope.sustain);
    write_optional_span(image, envelope.loop_span);
    image.push(u8::from(envelope.carry));
}

fn write_optional_span(image: &mut Vec<u8>, span: Option<EnvelopeSpan>) {
    image.push(u8::from(span.is_some()));
    let span = span.unwrap_or_default();
    image.push(span.start);
    image.push(span.end);
}

fn write_optional_pan(image: &mut Vec<u8>, pan: Option<I1F15>) {
    image.push(u8::from(pan.is_some()));
    push_u16(image, pan.unwrap_or(I1F15::ZERO).to_bits() as u16);
}

fn write_optional_byte(image: &mut Vec<u8>, value: Option<u8>) {
    image.push(u8::from(value.is_some()));
    image.push(value.unwrap_or(0));
}

fn write_optional_sustain_loop(image: &mut Vec<u8>, sustain: Option<SustainLoop>) {
    image.push(u8::from(sustain.is_some()));
    let sustain = sustain.unwrap_or(SustainLoop { mode: LoopMode::None, start: 0, end: 0 });
    image.push(loop_mode_code(sustain.mode));
    push_u32(image, sustain.start);
    push_u32(image, sustain.end);
}

fn push_u16(image: &mut Vec<u8>, value: u16) { image.extend_from_slice(&value.to_le_bytes()); }

fn push_u32(image: &mut Vec<u8>, value: u32) { image.extend_from_slice(&value.to_le_bytes()); }

/// A length or a count, as a `u32`. See [`Module::to_image`] for what saturation means.
fn push_length(image: &mut Vec<u8>, value: usize) { push_u32(image, u32::try_from(value).unwrap_or(u32::MAX)); }

fn push_text(image: &mut Vec<u8>, text: &str) {
    push_length(image, text.len());
    image.extend_from_slice(text.as_bytes());
}

fn module_flags_bits(flags: ModuleFlags) -> u8 {
    u8::from(flags.amiga_limits) | u8::from(flags.linear_slides) << 1 | u8::from(flags.fast_volume_slides) << 2 | u8::from(flags.stereo) << 3
}

